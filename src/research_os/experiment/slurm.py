"""Submitting an experiment to Slurm, and asking the scheduler what happened.

The abstraction is small on purpose: submit, poll, cancel. Everything else a
scheduler can do belongs to the researcher and their cluster documentation.

Three properties shape the implementation.

**The scheduler is the authority on job state.** A job's state comes from
``squeue`` while it is live and ``sacct`` once it is not, parsed from the
field-separated output those commands produce with ``--noheader --parsable2``.
No model is asked to interpret scheduler output, and the raw state string is
kept verbatim beside the mapped one, because a mapping is an interpretation.

**Nothing is built as a shell string.** A submission is a generated job script
plus an ``sbatch`` argument vector. The script is written by this module from
validated settings, and the experiment's own command goes into it as a properly
quoted argument vector -- generated by :func:`shlex.quote` over tokens that have
already been refused if they contained shell syntax at all, so the quoting is
belt to the spec module's braces.

**Remote is the same code with a prefix.** A cluster this machine is not part of
is reached as ``ssh <alias> <command...>``, where the alias comes from the
researcher's own SSH configuration. Research OS never holds a credential, never
takes a password, and never writes an SSH option; it names a host and lets the
researcher's agent do what it already does.

On a machine with no scheduler -- which is the machine this was written on --
every method reports ``UNAVAILABLE`` honestly rather than pretending.
"""

from __future__ import annotations

import shlex
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from research_os.automation.models import utc_now
from research_os.errors import SchedulerUnavailableError
from research_os.experiment.config import SlurmSettings
from research_os.experiment.models import (
    ExecutionState,
    ExecutorKind,
    ResourceUsage,
    SchedulerRecord,
)
from research_os.experiment.spec import ResolvedCommand

SBATCH = "sbatch"
SQUEUE = "squeue"
SACCT = "sacct"
SCANCEL = "scancel"
SSH = "ssh"

#: How long any one scheduler command may take before it is abandoned.
#:
#: Short. These are metadata queries; a login node that cannot answer in a
#: minute is a login node that is not going to answer.
SCHEDULER_TIMEOUT_SECONDS = 60

#: How Slurm's own state names map onto the controller's lifecycle.
#:
#: Anything not listed becomes ``UNKNOWN`` rather than being guessed at. A
#: scheduler state this build has not seen is a real thing that happened, and
#: silently rounding it to "failed" would misreport it.
STATE_MAP: dict[str, ExecutionState] = {
    "PENDING": ExecutionState.PENDING,
    "CONFIGURING": ExecutionState.PENDING,
    "REQUEUED": ExecutionState.PENDING,
    "RESIZING": ExecutionState.RUNNING,
    "RUNNING": ExecutionState.RUNNING,
    "COMPLETING": ExecutionState.RUNNING,
    "SUSPENDED": ExecutionState.RUNNING,
    "COMPLETED": ExecutionState.COMPLETED,
    "FAILED": ExecutionState.FAILED,
    "BOOT_FAIL": ExecutionState.FAILED,
    "NODE_FAIL": ExecutionState.FAILED,
    "OUT_OF_MEMORY": ExecutionState.FAILED,
    "DEADLINE": ExecutionState.FAILED,
    "CANCELLED": ExecutionState.CANCELLED,
    "PREEMPTED": ExecutionState.CANCELLED,
    "REVOKED": ExecutionState.CANCELLED,
    "TIMEOUT": ExecutionState.TIMED_OUT,
}


@dataclass(frozen=True, slots=True)
class SchedulerProbe:
    """What local inspection established about Slurm on this machine."""

    available: bool
    kind: ExecutorKind
    executables: dict[str, str | None] = field(default_factory=dict)
    ssh_host: str | None = None
    partitions: tuple[str, ...] = ()
    detail: str = ""

    @property
    def missing(self) -> tuple[str, ...]:
        return tuple(
            name for name, path in sorted(self.executables.items()) if path is None
        )


def probe(settings: SlurmSettings) -> SchedulerProbe:
    """Report whether an experiment could be submitted, without submitting one.

    Local inspection only. Running ``sinfo`` to see whether a cluster answers
    would be a network call in a command a researcher expects to be free, and it
    would fail for reasons that have nothing to do with whether Research OS is
    configured correctly.
    """

    if not settings.enabled:
        return SchedulerProbe(
            available=False,
            kind=settings.kind,
            detail=(
                "Slurm is not enabled in experiments.yaml. Set slurm.enabled to "
                "true and list the partitions you may submit to."
            ),
        )
    if settings.ssh_host:
        found = shutil.which(SSH)
        return SchedulerProbe(
            available=found is not None,
            kind=ExecutorKind.SLURM_SSH,
            executables={SSH: found},
            ssh_host=settings.ssh_host,
            partitions=tuple(settings.partitions),
            detail=(
                f"scheduler commands run as 'ssh {settings.ssh_host} ...'; "
                "whether that host answers is decided by your own SSH "
                "configuration and agent"
                if found
                else "ssh is not installed, so a remote cluster cannot be reached"
            ),
        )
    executables = {name: shutil.which(name) for name in (SBATCH, SQUEUE, SACCT)}
    missing = [name for name, path in executables.items() if path is None]
    return SchedulerProbe(
        available=not missing,
        kind=ExecutorKind.SLURM,
        executables=executables,
        partitions=tuple(settings.partitions),
        detail=(
            "sbatch, squeue, and sacct are on PATH"
            if not missing
            else f"not on PATH: {', '.join(missing)}. This machine is not a Slurm "
            "submit host; set slurm.ssh_host to submit from one that is."
        ),
    )


@dataclass
class SlurmExecutor:
    """Submit, poll, and cancel Slurm jobs, locally or over SSH."""

    settings: SlurmSettings
    timeout_seconds: int = SCHEDULER_TIMEOUT_SECONDS

    # -- submission ------------------------------------------------------

    def build_script(
        self,
        command: ResolvedCommand,
        *,
        job_name: str,
        partition: str,
        working_directory: str,
        time_limit: str,
        stdout_path: str,
        stderr_path: str,
    ) -> str:
        """Return the batch script for one experiment.

        Every ``#SBATCH`` line comes from a validated setting. The experiment's
        own command is written as a quoted argument vector rather than as a
        line of shell the caller supplied, so the only thing the shell on the
        compute node does is run exactly the argv the controller resolved.
        """

        if not self.settings.allows(partition):
            raise SchedulerUnavailableError(
                f"partition {partition!r} is not in this project's allowed "
                f"partitions ({', '.join(self.settings.partitions) or 'none'}). "
                "A job is submitted only to a partition you listed."
            )
        directives = [
            f"#SBATCH --job-name={job_name}",
            f"#SBATCH --partition={partition}",
            f"#SBATCH --time={time_limit}",
            f"#SBATCH --output={stdout_path}",
            f"#SBATCH --error={stderr_path}",
            f"#SBATCH --chdir={working_directory}",
        ]
        if self.settings.account:
            directives.append(f"#SBATCH --account={self.settings.account}")
        if self.settings.default_cpus:
            directives.append(f"#SBATCH --cpus-per-task={self.settings.default_cpus}")
        if self.settings.default_memory_mb:
            directives.append(f"#SBATCH --mem={self.settings.default_memory_mb}")
        quoted = " ".join(shlex.quote(token) for token in command.argv)
        return "\n".join(
            [
                "#!/bin/bash",
                *directives,
                "set -euo pipefail",
                "",
                "# Generated by Research OS. The line below is the resolved",
                "# argument vector, quoted; nothing here was written by a model.",
                quoted,
                "",
            ]
        )

    def submit(
        self,
        script_path: Path,
        *,
        partition: str,
    ) -> SchedulerRecord:
        """Submit one prepared script and return the scheduler's job id."""

        if not self.settings.allows(partition):
            raise SchedulerUnavailableError(
                f"partition {partition!r} is not in this project's allowed partitions"
            )
        completed = self._run([SBATCH, "--parsable", str(script_path)])
        job_id = (completed.stdout or "").strip().split(";")[0].strip()
        if completed.returncode != 0 or not job_id:
            raise SchedulerUnavailableError(
                f"sbatch refused the submission (exit {completed.returncode}): "
                + ((completed.stderr or "").strip()[:400] or "no error text")
            )
        return SchedulerRecord(
            job_id=job_id,
            partition=partition,
            account=self.settings.account,
            submitted_at=utc_now(),
            raw_state="SUBMITTED",
            host=self.settings.ssh_host,
        )

    # -- polling ---------------------------------------------------------

    def poll(
        self, job_id: str
    ) -> tuple[ExecutionState, SchedulerRecord, ResourceUsage]:
        """Ask the scheduler what became of one job.

        ``squeue`` first, because a live job is only there; then ``sacct``,
        which is the only one that knows about a job that has finished. A job
        neither knows about is ``UNKNOWN`` -- it may have aged out of accounting
        -- and saying so is more useful than calling it failed.
        """

        live = self._run(
            [SQUEUE, "--job", job_id, "--noheader", "--format=%T|%R", "--states=all"]
        )
        if live.returncode == 0 and (live.stdout or "").strip():
            raw, _, reason = (live.stdout or "").strip().splitlines()[0].partition("|")
            state = map_state(raw)
            return (
                state,
                SchedulerRecord(
                    job_id=job_id,
                    raw_state=raw.strip(),
                    reason=reason.strip(),
                    polled_at=utc_now(),
                    host=self.settings.ssh_host,
                    partition=None,
                ),
                ResourceUsage(observed_by="squeue"),
            )

        history = self._run(
            [
                SACCT,
                "--jobs",
                job_id,
                "--noheader",
                "--parsable2",
                "--format=JobID,State,ExitCode,Elapsed,TotalCPU,MaxRSS,NNodes,Partition",
            ]
        )
        if history.returncode != 0 or not (history.stdout or "").strip():
            return (
                ExecutionState.UNKNOWN,
                SchedulerRecord(
                    job_id=job_id,
                    raw_state="",
                    reason=(
                        "neither squeue nor sacct knows this job; it may have aged "
                        "out of accounting"
                    ),
                    polled_at=utc_now(),
                    host=self.settings.ssh_host,
                ),
                ResourceUsage(observed_by="nothing could be asked"),
            )
        return parse_sacct(history.stdout or "", job_id, host=self.settings.ssh_host)

    def cancel(self, job_id: str) -> SchedulerRecord:
        completed = self._run([SCANCEL, job_id])
        return SchedulerRecord(
            job_id=job_id,
            raw_state="CANCELLED" if completed.returncode == 0 else "",
            reason=(
                "cancelled by the researcher"
                if completed.returncode == 0
                else (completed.stderr or "").strip()[:400]
            ),
            polled_at=utc_now(),
            host=self.settings.ssh_host,
        )

    # -- transport -------------------------------------------------------

    def argv_for(self, command: list[str]) -> list[str]:
        """Return the argument vector that actually runs one scheduler command.

        Local is the command itself. Remote prefixes it with ``ssh <alias>`` and
        nothing else: no ``-o`` options, no user, no port, no identity file.
        Everything about how that host is reached already lives in the
        researcher's SSH configuration, which is also where their credentials
        are, and Research OS has no business duplicating either.
        """

        if not self.settings.ssh_host:
            return command
        return [SSH, self.settings.ssh_host, *command]

    def _run(self, command: list[str]) -> subprocess.CompletedProcess[str]:
        argv = self.argv_for(command)
        if shutil.which(argv[0]) is None:
            raise SchedulerUnavailableError(
                f"{argv[0]} is not on PATH, so this machine cannot talk to a "
                "Slurm scheduler"
            )
        try:
            return subprocess.run(
                argv,
                check=False,
                capture_output=True,
                text=True,
                stdin=subprocess.DEVNULL,
                timeout=self.timeout_seconds,
            )
        except subprocess.TimeoutExpired as exc:
            raise SchedulerUnavailableError(
                f"{' '.join(command)} did not answer within {self.timeout_seconds}s"
            ) from exc
        except OSError as exc:
            raise SchedulerUnavailableError(
                f"{' '.join(command)} could not be run: {exc}"
            ) from exc


def map_state(raw: str) -> ExecutionState:
    """Map one Slurm state name onto the controller's lifecycle.

    Slurm suffixes some states with a reason, as in ``CANCELLED by 1234``, so
    the first word decides. Anything unrecognised is ``UNKNOWN``: a state this
    build has not seen is a real thing that happened, and rounding it to
    "failed" would misreport it.
    """

    token = (raw or "").strip().split()[0].upper() if (raw or "").strip() else ""
    return STATE_MAP.get(token, ExecutionState.UNKNOWN)


def parse_sacct(
    output: str, job_id: str, *, host: str | None = None
) -> tuple[ExecutionState, SchedulerRecord, ResourceUsage]:
    """Read ``sacct --parsable2`` output for one job.

    ``sacct`` reports the job and then each of its steps, and the steps are the
    only rows that carry ``MaxRSS``. So the job row decides the state and the
    exit code, and the step rows are searched for the resource numbers -- taking
    the maximum, because peak memory across steps is what a reader means by the
    job's peak memory.
    """

    state = ExecutionState.UNKNOWN
    record = SchedulerRecord(job_id=job_id, polled_at=utc_now(), host=host)
    usage = ResourceUsage(observed_by="sacct")
    max_rss: int | None = None

    for line in output.splitlines():
        fields = line.split("|")
        if len(fields) < 8:
            continue
        row_id, raw_state, exit_code, elapsed, total_cpu, rss, nodes, partition = (
            fields[:8]
        )
        rss_value = _memory_kb(rss)
        if rss_value is not None:
            max_rss = rss_value if max_rss is None else max(max_rss, rss_value)
        if row_id.strip() != job_id:
            continue
        state = map_state(raw_state)
        record = SchedulerRecord(
            job_id=job_id,
            raw_state=raw_state.strip(),
            exit_code=_exit_code(exit_code),
            signal=_signal(exit_code),
            partition=partition.strip() or None,
            polled_at=utc_now(),
            host=host,
        )
        usage = ResourceUsage(
            wall_clock_seconds=_elapsed_seconds(elapsed),
            cpu_seconds=_elapsed_seconds(total_cpu),
            node_count=int(nodes) if nodes.strip().isdigit() else None,
            observed_by="sacct",
        )
    if max_rss is not None:
        usage = usage.model_copy(update={"max_rss_kb": max_rss})
    return state, record, usage


def _exit_code(value: str) -> int | None:
    """Return the exit code from ``sacct``'s ``code:signal`` pair."""

    head = value.split(":")[0].strip()
    return int(head) if head.isdigit() else None


def _signal(value: str) -> int | None:
    parts = value.split(":")
    if len(parts) < 2:
        return None
    tail = parts[1].strip()
    return int(tail) if tail.isdigit() and int(tail) != 0 else None


def _elapsed_seconds(value: str) -> float | None:
    """Parse Slurm's elapsed-time forms into seconds, or return ``None``.

    Slurm writes ``DD-HH:MM:SS``, ``HH:MM:SS``, ``MM:SS``, and for CPU time
    ``MM:SS.mmm``. A form this does not recognise becomes ``None`` rather than
    a guess.
    """

    text = (value or "").strip()
    if not text:
        return None
    days = 0
    if "-" in text:
        head, _, text = text.partition("-")
        if not head.isdigit():
            return None
        days = int(head)
    parts = text.split(":")
    try:
        numbers = [float(item) for item in parts]
    except ValueError:
        return None
    if len(numbers) == 3:
        hours, minutes, seconds = numbers
    elif len(numbers) == 2:
        hours, (minutes, seconds) = 0.0, numbers
    elif len(numbers) == 1:
        hours, minutes, seconds = 0.0, 0.0, numbers[0]
    else:
        return None
    return days * 86_400 + hours * 3_600 + minutes * 60 + seconds


def _memory_kb(value: str) -> int | None:
    """Parse Slurm's memory forms (``1234K``, ``12M``, ``1.5G``) into kilobytes."""

    text = (value or "").strip().upper()
    if not text:
        return None
    scale = {"K": 1, "M": 1024, "G": 1024 * 1024, "T": 1024 * 1024 * 1024}
    unit = text[-1]
    if unit in scale:
        head = text[:-1]
        multiplier = scale[unit]
    else:
        head, multiplier = text, 1
    try:
        return int(float(head) * multiplier)
    except ValueError:
        return None
